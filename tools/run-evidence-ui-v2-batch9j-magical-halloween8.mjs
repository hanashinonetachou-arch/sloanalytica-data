#!/usr/bin/env node
import { execSync } from 'node:child_process';
import fs from 'node:fs';
const id='L_MAGICAL_HALLOWEEN8_FE';
const run=cmd=>execSync(cmd,{stdio:'inherit'});
const expectedInputs=['INP_EVI_TROPHY','INP_EVI_PAYOUT_DISPLAY','INP_EVI_ALICE_PATTERN','INP_EVI_ART_END_SCREEN'];
const expectedObs=['OBS_EVI_TROPHY','OBS_EVI_PAYOUT_DISPLAY','OBS_EVI_ALICE_PATTERN','OBS_EVI_ART_END_SCREEN'];
const expectedRefs=['RE_TROPHY_2PLUS','RE_TROPHY_3PLUS','RE_TROPHY_4PLUS','RE_TROPHY_5PLUS','RE_TROPHY_6','RE_PAYOUT_2PLUS','RE_PAYOUT_4PLUS','RE_PAYOUT_6','RE_ALICE_END_2PLUS','RE_ALICE_BOTH_5PLUS','RE_ART_END_2PLUS','RE_ART_END_4PLUS','RE_ART_END_6'];
run('node tools/migrate-evidence-ui-v2-batch9j-magical-halloween8.mjs');
run(`node tools/validate-selection-data.mjs research/${id}/selection-data.json research/${id}/research-data.json`);
run(`node tools/validate-machine-observation-data.mjs research/${id}/machine-observation-data.json`);
run('node tools/validate-ui-design-data.mjs .');
run(`node tools/audit-ui-design-observation-linkage.mjs ${id} --strict-v2`);
run(`node tools/four-layer-pipeline-gate.mjs ${id}`);
run(`npm run machine:pipeline -- ${id} --check --skip-repo-checks`);
run(`npm run machine:pipeline -- ${id} --skip-repo-checks`);
run('node tools/validate-evidence-ui-all.mjs');
run('node tools/validate-ui-design-data.mjs .');
run(`node tools/audit-ui-design-observation-linkage.mjs ${id} --strict-v2`);
run(`node tools/four-layer-pipeline-gate.mjs ${id}`);
const pkg=JSON.parse(fs.readFileSync(`machines/${id}/machine-package.json`,'utf8'));
const inputIds=new Set((pkg.inputs?.inputs??[]).map(x=>x.id));
if(inputIds.has('INP_EVI_SETTING_FLOOR')) throw new Error(`${id}: legacy floor remains`);
for(const iid of expectedInputs) if(!inputIds.has(iid)) throw new Error(`${id}: missing ${iid}`);
if(pkg.machine?.machineDataVersion!=='0.1.1') throw new Error(`${id}: version mismatch`);
const refs=new Set((pkg.evidence?.evidences??[]).flatMap(x=>x.sourceEvidenceRefs??[]));
for(const ref of expectedRefs) if(!refs.has(ref)) throw new Error(`${id}: missing ${ref}`);
const obs=JSON.parse(fs.readFileSync(`research/${id}/machine-observation-data.json`,'utf8'));
if((obs.observations??[]).some(x=>x.observationId==='OBS_SETTING_EVIDENCE')) throw new Error(`${id}: legacy observation remains`);
for(const oid of expectedObs) if(!(obs.observations??[]).some(x=>x.observationId===oid)) throw new Error(`${id}: missing ${oid}`);
for(const p of [`machines/${id}/machine-package.json`,`research/${id}/statistics-report.json`,`research/${id}/difficulty-report.json`,`research/${id}/setting-band-report.json`]) if(!fs.existsSync(p)||fs.statSync(p).size===0) throw new Error(`${id}: missing ${p}`);
for(const p of ['catalog.json','difficulty-catalog.json','machine-registry.json']) if(!fs.existsSync(p)||fs.statSync(p).size===0) throw new Error(`missing ${p}`);
console.log('Evidence UI v2 batch9j Magical Halloween8 generated contracts: PASS');
